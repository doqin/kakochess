/**
 * Fast synchronous evaluation function.
 * Returns a score from the perspective of the side whose turn it is.
 */
export function evaluateBoardSync(game) {
  const turn = game.turn();
  let score = 0;
  const board = game.board();

  for (let r = 0; r < 8; r++) {
    for (let f = 0; f < 8; f++) {
      const piece = board[r][f];
      if (piece) {
        const type = piece.type;
        const color = piece.color;
        const isMyPiece = (color === turn);
        
        let val = PIECE_VALUES[type];
        
        // Add positional bonus from PST (flip for black)
        // Note: PST tables are usually stored for White.
        // If it's my piece, I want my PST bonus.
        // If it's White, PST row = rank. If Black piece, PST row = 7-rank.
        const pstRow = color === 'w' ? r : 7 - r;
        val += PST[type][pstRow][f];

        score += isMyPiece ? val : -val;
      }
    }
  }

  return score;
}
